"""List every SEC filing behind outputs/sec_cruise_quarterly.csv, with a link to each one.

Writes outputs/sec_filings_used.csv and docs/SEC_FILINGS.md. Run after src.sec_cruise_data
(it reads the cached EDGAR filing indexes in data/sec/, so it needs no network access).
"""
import json

import pandas as pd

from src import config
from src.sec_cruise_data import CACHE, COMPANIES

LEGAL_NAMES = {
    "Royal Caribbean": "Royal Caribbean Cruises Ltd.",
    "Carnival": "Carnival Corporation & plc",
    "Norwegian": "Norwegian Cruise Line Holdings Ltd.",
}


def edgar_browse(cik: str, form: str) -> str:
    return f"https://www.sec.gov/cgi-bin/browse-edgar?action=getcompany&CIK={cik}&type={form}&dateb=&owner=include&count=40"


def filings_used() -> pd.DataFrame:
    data = pd.read_csv(config.OUTPUTS / "sec_cruise_quarterly.csv", parse_dates=["quarter_end"])
    rows = []
    for name, cfg in COMPANIES.items():
        cik = cfg["cik"]
        sub = json.loads((CACHE / f"sub_{cik}.json").read_text(encoding="utf-8"))
        r = sub["filings"]["recent"]
        d = data[data["company"] == name]
        q10 = set(d.loc[d["source"] == "10-Q", "quarter_end"].dt.date.astype(str))
        q4 = d.loc[d["source"] != "10-Q", "quarter_end"]
        q4_years = set(q4.dt.year)
        for i, form in enumerate(r["form"]):
            if form not in ("10-Q", "10-K"):
                continue
            acc, period = r["accessionNumber"][i], r["reportDate"][i]
            if not (CACHE / f"{cik}_{acc}.htm").exists() or not period:
                continue
            year = int(period[:4])
            used = []
            if form == "10-Q" and period in q10:
                used.append(f"Quarter ending {period}")
            if form == "10-Q" and year in q4_years and period in q10 and period[5:7] in ("09", "08"):
                used.append(f"Nine-month YTD, used to derive Q4 {year}")
            if form == "10-K" and year in q4_years:
                used.append(f"Full year {year}, used to derive Q4 {year}")
            if not used:
                continue
            url = f"https://www.sec.gov/Archives/edgar/data/{int(cik)}/{acc.replace('-', '')}/{r['primaryDocument'][i]}"
            rows.append({"company": name, "legal_name": LEGAL_NAMES[name], "cik": cik, "form": form,
                         "period_end": period, "filed": r["filingDate"][i], "accession": acc,
                         "used_for": "; ".join(used), "url": url})
    return pd.DataFrame(rows).sort_values(["company", "period_end"]).reset_index(drop=True)


def citation(row) -> str:
    return (f"{row.legal_name} ({row.filed[:4]}). *Form {row.form} for the period ended {row.period_end}*. "
            f"U.S. Securities and Exchange Commission. Accession No. {row.accession}. {row.url}")


def write_markdown(f: pd.DataFrame) -> None:
    lines = [
        "# SEC Filings Used",
        "",
        "Every 10-Q and 10-K filing that supplies a number in `outputs/sec_cruise_quarterly.csv`, with a direct link to "
        "the document on SEC EDGAR. This file is generated by `python -m src.sec_citations`; the same list is in "
        "`outputs/sec_filings_used.csv`.",
        "",
        f"**{len(f)} filings:** " + ", ".join(f"{c} {n}" for c, n in f.groupby("company").size().items()) + ".",
        "",
        "In each filing, the numbers come from the operating statistics table in Management's Discussion and Analysis "
        "(passengers carried, passenger cruise days, capacity days, occupancy). Quarterly revenue comes from the "
        "company's XBRL financial data, which is filed with the same reports.",
        "",
    ]
    for name in COMPANIES:
        g = f[f["company"] == name]
        cik = COMPANIES[name]["cik"]
        lines += [
            f"## {LEGAL_NAMES[name]} (CIK {cik})",
            "",
            f"All filings: [10-Q list]({edgar_browse(cik, '10-Q')}) · [10-K list]({edgar_browse(cik, '10-K')}) · "
            f"[XBRL company facts](https://data.sec.gov/api/xbrl/companyfacts/CIK{cik}.json)",
            "",
            "| Form | Period ended | Filed | Used for | Link |",
            "|---|---|---|---|---|",
        ]
        for r in g.itertuples():
            lines.append(f"| {r.form} | {r.period_end} | {r.filed} | {r.used_for} | "
                         f"[{r.accession}]({r.url}) |")
        lines.append("")
    lines += ["## Citations", "", "Formatted references for every filing above.", ""]
    lines += [f"{i}. {citation(r)}" for i, r in enumerate(f.itertuples(), 1)]
    (config.ROOT / "docs").mkdir(exist_ok=True)
    (config.ROOT / "docs" / "SEC_FILINGS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def run() -> pd.DataFrame:
    f = filings_used()
    f.to_csv(config.OUTPUTS / "sec_filings_used.csv", index=False)
    write_markdown(f)
    return f


if __name__ == "__main__":
    f = run()
    print(f.groupby(["company", "form"]).size())
    print(f.tail(3).to_string())
